"""Tiny procedural mesh toolkit -> Wavefront OBJ (right-handed, CCW front faces, Y up)."""
import numpy as np, math

def sgnpow(x, p):
    return np.sign(x) * np.abs(x) ** p

class Mesh:
    def __init__(self):
        self.parts = {}   # material -> list of (V,F,smooth)
    def add(self, mat, V, F, smooth=True, closed=True):
        V = np.asarray(V, float); F = np.asarray(F, int)
        if closed:
            V, F = orient(V, F)
        self.parts.setdefault(mat, []).append((V, F, smooth))
    def write(self, path, name):
        out = [f"# {name} - generated by Tools/make_models.py", f"o {name}"]
        base = 1
        for mat, lst in self.parts.items():
            out.append(f"usemtl {mat}")
            for V, F, smooth in lst:
                if smooth:
                    N = vert_normals(V, F)
                    for v in V: out.append("v %.5f %.5f %.5f" % tuple(v))
                    for n in N: out.append("vn %.4f %.4f %.4f" % tuple(n))
                    for f in F:
                        a, b, c = f + base
                        out.append(f"f {a}//{a} {b}//{b} {c}//{c}")
                    base += len(V)
                else:
                    for f in F:
                        p = V[f]; n = np.cross(p[1]-p[0], p[2]-p[0]); l = np.linalg.norm(n)
                        n = n / l if l > 1e-12 else np.array([0, 1, 0])
                        for q in p: out.append("v %.5f %.5f %.5f" % tuple(q))
                        for _ in range(3): out.append("vn %.4f %.4f %.4f" % tuple(n))
                        out.append(f"f {base}//{base} {base+1}//{base+1} {base+2}//{base+2}")
                        base += 3
        open(path, "w").write("\n".join(out) + "\n")
    def triangles(self):
        tris = []
        for mat, lst in self.parts.items():
            for V, F, _ in lst:
                for f in F: tris.append((mat, V[f]))
        return tris

def vert_normals(V, F):
    N = np.zeros_like(V)
    p = V[F]
    fn = np.cross(p[:, 1]-p[:, 0], p[:, 2]-p[:, 0])
    for i in range(3): np.add.at(N, F[:, i], fn)
    l = np.linalg.norm(N, axis=1, keepdims=True); l[l < 1e-12] = 1
    return N / l

def signed_volume(V, F):
    p = V[F]
    return np.einsum('ij,ij->i', p[:, 0], np.cross(p[:, 1], p[:, 2])).sum() / 6.0

def orient_outward(V, F, c):
    c = np.array(c, float); p = V[F]
    n = np.cross(p[:, 1]-p[:, 0], p[:, 2]-p[:, 0]); m = p.mean(axis=1) - c
    return V, (F[:, ::-1].copy() if np.einsum('ij,ij->i', n, m).sum() < 0 else F)

def orient(V, F):
    if signed_volume(V, F) < 0: F = F[:, ::-1].copy()
    return V, F

def grid_faces(nr, nc, wrap=True):
    F = []
    for i in range(nr - 1):
        for j in range(nc if wrap else nc - 1):
            a = i*nc + j; b = i*nc + (j+1) % nc; c = (i+1)*nc + j; d = (i+1)*nc + (j+1) % nc
            F += [[a, b, d], [a, d, c]]
    return F

def superellipsoid(c, r, e1=1.0, e2=1.0, nl=16, nm=32, lat0=-90, lat1=90):
    """e=1 sphere, e<1 boxy. Returns V,F (closed if full range)."""
    V = []
    for i in range(nl + 1):
        phi = math.radians(lat0 + (lat1 - lat0) * i / nl)
        for j in range(nm):
            th = 2*math.pi*j/nm
            x = sgnpow(math.cos(phi), e1) * sgnpow(math.cos(th), e2)
            z = sgnpow(math.cos(phi), e1) * sgnpow(math.sin(th), e2)
            y = sgnpow(math.sin(phi), e1)
            V.append([c[0]+r[0]*x, c[1]+r[1]*y, c[2]+r[2]*z])
    return np.array(V), np.array(grid_faces(nl + 1, nm))

def loft(stations, nm=40):
    """stations: (z, cx, cy, w, h, n) along +Z. Closed with end caps."""
    V = []
    for (z, cx, cy, w, h, n) in stations:
        for j in range(nm):
            th = 2*math.pi*j/nm
            V.append([cx + w*sgnpow(math.cos(th), 2.0/n), cy + h*sgnpow(math.sin(th), 2.0/n), z])
    V = np.array(V); ns = len(stations)
    F = grid_faces(ns, nm)
    for k in (0, ns-1):
        zc, cx, cy = stations[k][0], stations[k][1], stations[k][2]
        V = np.vstack([V, [cx, cy, zc]]); ci = len(V)-1
        for j in range(nm):
            a = k*nm + j; b = k*nm + (j+1) % nm
            F.append([ci, a, b])
    return V, np.array(F)

def cylinder(p0, p1, r0, r1=None, n=24, caps=True):
    r1 = r0 if r1 is None else r1
    p0 = np.array(p0, float); p1 = np.array(p1, float)
    ax = p1 - p0; L = np.linalg.norm(ax); ax /= L
    t = np.array([1, 0, 0]) if abs(ax[0]) < .9 else np.array([0, 1, 0])
    u = np.cross(ax, t); u /= np.linalg.norm(u); v = np.cross(ax, u)
    V = []
    for p, r in ((p0, r0), (p1, r1)):
        for j in range(n):
            a = 2*math.pi*j/n
            V.append(p + r*(math.cos(a)*u + math.sin(a)*v))
    V = np.array(V); F = []
    for j in range(n):
        a = j; b = (j+1) % n
        F += [[a, b, n+b], [a, n+b, n+a]]
    if caps:
        V = np.vstack([V, p0, p1]); c0 = len(V)-2; c1 = len(V)-1
        for j in range(n):
            b = (j+1) % n
            F.append([c0, b, j]); F.append([c1, n+j, n+b])
    return V, np.array(F)

def torus(c, R, r, axis=2, nu=40, nv=12):
    V = []
    for i in range(nu):
        a = 2*math.pi*i/nu
        for j in range(nv):
            b = 2*math.pi*j/nv
            ring = R + r*math.cos(b); h = r*math.sin(b)
            p = [ring*math.cos(a), ring*math.sin(a), h]   # axis = local z
            V.append(p)
    V = np.array(V)
    if axis == 1: V = V[:, [0, 2, 1]]
    if axis == 0: V = V[:, [2, 0, 1]]
    V = V + np.array(c)
    F = []
    for i in range(nu):
        for j in range(nv):
            a = i*nv + j; b = i*nv + (j+1) % nv; c2 = ((i+1) % nu)*nv + j; d = ((i+1) % nu)*nv + (j+1) % nv
            F += [[a, b, d], [a, d, c2]]
    return V, np.array(F)

def box(c, s):
    cx, cy, cz = c; sx, sy, sz = [x/2 for x in s]
    V = np.array([[cx+dx*sx, cy+dy*sy, cz+dz*sz] for dx in (-1, 1) for dy in (-1, 1) for dz in (-1, 1)])
    F = [[0,1,3],[0,3,2],[4,6,7],[4,7,5],[0,4,5],[0,5,1],[2,3,7],[2,7,6],[0,2,6],[0,6,4],[1,5,7],[1,7,3]]
    return V, np.array(F)

def prism(poly, y0, y1):
    """Extrude convex-ish polygon [(x,z)...] between heights y0..y1 (arrays allowed per vertex)."""
    n = len(poly)
    y0 = np.broadcast_to(np.asarray(y0, float), (n,)); y1 = np.broadcast_to(np.asarray(y1, float), (n,))
    V = np.array([[x, y0[i], z] for i, (x, z) in enumerate(poly)] + [[x, y1[i], z] for i, (x, z) in enumerate(poly)])
    cx = np.mean([p[0] for p in poly]); cz = np.mean([p[1] for p in poly])
    V = np.vstack([V, [cx, y0.mean(), cz], [cx, y1.mean(), cz]]); cb = 2*n; ct = 2*n+1
    F = []
    for i in range(n):
        j = (i+1) % n
        F += [[i, j, n+j], [i, n+j, n+i], [cb, j, i], [ct, n+i, n+j]]
    return V, np.array(F)

def rot(V, axis, deg, pivot=(0, 0, 0)):
    a = math.radians(deg); c, s = math.cos(a), math.sin(a)
    R = {0: [[1,0,0],[0,c,-s],[0,s,c]], 1: [[c,0,s],[0,1,0],[-s,0,c]], 2: [[c,-s,0],[s,c,0],[0,0,1]]}[axis]
    pv = np.array(pivot, float)
    return (np.asarray(V) - pv) @ np.array(R).T + pv

def mirror_x(V, F):
    V2 = np.array(V).copy(); V2[:, 0] *= -1
    return V2, np.array(F)[:, ::-1].copy()

def tube(p0, p1, r, n=6):
    return cylinder(p0, p1, r, r, n=n)
